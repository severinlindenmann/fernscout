// Regenerates lib/timeZoneCountry.ts — IANA time zone → ISO 3166-1 alpha-2.
//
//   node scripts/build-timezone-country.mjs [path/to/zone.tab]
//
// Reads the IANA tz database's zone.tab (public domain), which names one
// country per zone — the platform's own copy at /usr/share/zoneinfo by
// default. Run once, commit the output; nothing at build or run time reads the
// file. A zone with no row (UTC, Etc/GMT+3, an alias) resolves to nothing.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const SOURCE = process.argv[2] ?? "/usr/share/zoneinfo/zone.tab";

/** @type {Record<string,string>} */
const byZone = {};
for (const line of fs.readFileSync(SOURCE, "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [code, , zone] = line.split("\t");
  if (/^[A-Z]{2}$/.test(code) && zone) byZone[zone] = code;
}

const lines = Object.keys(byZone)
  .sort()
  .map((z) => `  ${JSON.stringify(z)}: ${JSON.stringify(byZone[z])},`);

fs.writeFileSync(
  path.join(ROOT, "lib/timeZoneCountry.ts"),
  `// Generated by scripts/build-timezone-country.mjs — do not edit by hand.\n` +
    `// Source: IANA tz database zone.tab (public domain). Re-run the script to refresh it.\n\n` +
    `/** IANA time zone → ISO 3166-1 alpha-2, one country per zone. */\n` +
    `export const COUNTRY_FOR_TIME_ZONE: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`wrote ${lines.length} zones`);
