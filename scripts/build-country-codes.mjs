// Regenerates lib/countryCodes.ts — country name → ISO 3166-1 alpha-2.
//
//   node scripts/build-country-codes.mjs
//
// The names come out of the GeoNames country block already committed inside
// lib/ingest/data/places.bin.gz, so this adds no dependency and no download.
// The output is a plain module because `lib/flags.ts` is imported by client
// components: the 2.9 MB blob must never reach a browser, and a few kilobytes
// of names must not require a build step to read.
//
// It exists because the table it replaces was 44 countries chosen by hand —
// "places we're likely to pass through" — which had no United States, Canada
// or United Kingdom in it. A self-hosted journal is somebody else's travel.
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const ROOT = path.join(import.meta.dirname, "..");
const MAGIC = "RPGEO1\0\0";

const buf = zlib.gunzipSync(fs.readFileSync(path.join(ROOT, "lib/ingest/data/places.bin.gz")));
if (buf.subarray(0, MAGIC.length).toString("latin1") !== MAGIC) {
  throw new Error("places.bin.gz is not a place index (bad magic).");
}
const countryCount = buf.readUInt32BE(MAGIC.length + 4);

/**
 * The one spelling both sides agree on. Must stay identical to `normalise`
 * in lib/flags.ts, or a name in the table becomes unreachable.
 *
 * GeoNames writes "The Netherlands" and "Côte d'Ivoire"; people write
 * "Netherlands" and "Cote d'Ivoire". Folding accents, straightening
 * apostrophes and dropping a leading "the" makes those the same key.
 */
function normalise(name) {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[\u2018\u2019\u02bc]/g, "'")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim()
    .replace(/^the /, "");
}

let at = MAGIC.length + 12;
/** @type {Record<string,string>} */
const byName = {};
for (let i = 0; i < countryCount; i++) {
  const code = buf.subarray(at, at + 2).toString("latin1");
  const nameLen = buf.readUInt8(at + 2);
  const name = buf.subarray(at + 3, at + 3 + nameLen).toString("utf8");
  at += 3 + nameLen;
  if (/^[A-Z]{2}$/.test(code) && name) byName[normalise(name)] = code;
}

/** Names people actually write, which GeoNames spells its own way. */
const ALIASES = {
  "united states of america": "US",
  usa: "US",
  "u.s.a.": "US",
  america: "US",
  uk: "GB",
  "united kingdom of great britain and northern ireland": "GB",
  england: "GB",
  scotland: "GB",
  wales: "GB",
  "northern ireland": "GB",
  holland: "NL",
  "the netherlands": "NL",
  "czech republic": "CZ",
  "south korea": "KR",
  "north korea": "KP",
  "ivory coast": "CI",
  burma: "MM",
  "cape verde": "CV",
  "east timor": "TL",
  vatican: "VA",
  uae: "AE",
  "cote d'ivoire": "CI",
  "cote divoire": "CI",
  "cabo verde": "CV",
  "eswatini": "SZ",
  "swaziland": "SZ",
  "myanmar (burma)": "MM",
  "timor-leste": "TL",
  "vatican city": "VA",
  "holy see": "VA",
  "macedonia": "MK",
  "north macedonia": "MK",
  "russian federation": "RU",
  "republic of ireland": "IE",
};
for (const [name, code] of Object.entries(ALIASES)) byName[normalise(name)] = code;

const sorted = Object.keys(byName).sort();
const lines = sorted.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(byName[n])},`);

fs.writeFileSync(
  path.join(ROOT, "lib/countryCodes.ts"),
  `// Generated by scripts/build-country-codes.mjs — do not edit by hand.\n` +
    `// Source: GeoNames countryInfo (CC BY 4.0), via lib/ingest/data/places.bin.gz,\n` +
    `// plus the aliases people actually type. Re-run the script to refresh it.\n\n` +
    `/** Lower-cased country name → ISO 3166-1 alpha-2. */\n` +
    `export const COUNTRY_CODES: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`Wrote lib/countryCodes.ts — ${sorted.length} names.`);
