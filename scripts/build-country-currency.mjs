// Regenerates lib/countryCurrency.ts — ISO 3166-1 alpha-2 → ISO 4217.
//
//   node scripts/build-country-currency.mjs
//
// Unlike scripts/build-country-codes.mjs, the currency column is not part of
// the packed geodata index (lib/ingest/geo.ts ships names and coordinates,
// not currencies), so this downloads GeoNames' own countryInfo.txt — the same
// source, same licence (CC BY 4.0) — and writes the plain module. Run once,
// commit the output; nothing at build or run time needs the network.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const URL = "https://download.geonames.org/export/dump/countryInfo.txt";

const res = await fetch(URL);
if (!res.ok) throw new Error(`fetching countryInfo.txt: ${res.status} ${res.statusText}`);
const text = await res.text();

/** @type {Record<string,string>} */
const byCode = {};
for (const line of text.split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const cols = line.split("\t");
  const code = cols[0];
  const currency = cols[10];
  // A handful of rows carry no currency at all (Antarctica) — one country,
  // one entry, and nothing to default a cost line to there.
  if (/^[A-Z]{2}$/.test(code) && /^[A-Z]{3}$/.test(currency ?? "")) byCode[code] = currency;
}

const sorted = Object.keys(byCode).sort();
const lines = sorted.map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify(byCode[c])},`);

fs.writeFileSync(
  path.join(ROOT, "lib/countryCurrency.ts"),
  `// Generated by scripts/build-country-currency.mjs — do not edit by hand.\n` +
    `// Source: GeoNames countryInfo.txt (CC BY 4.0). Re-run the script to refresh it.\n\n` +
    `/** ISO 3166-1 alpha-2 → ISO 4217. One currency per country, which is what the\n` +
    ` * source carries — the eurozone collapses correctly, a country running two\n` +
    ` * in parallel gets one. See lib/countryCurrency.ts's caller for why that is\n` +
    ` * tolerable: this is a default a writer overrides per line, never a\n` +
    ` * conversion. */\n` +
    `export const CURRENCY_FOR_COUNTRY: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`Wrote lib/countryCurrency.ts — ${sorted.length} countries.`);
