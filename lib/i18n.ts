/**
 * The singular of a counted string, when there is one.
 *
 * "1 trips" and "1 Countries" were both on the trips page, which is what a
 * language with two forms looks like when the code has none.
 *
 * A `<key>.one` entry beside the plural, and nothing more: these are counts of
 * days, countries and trips, and no language this project ships needs a third
 * form for them. Where a language does not inflect after a number at all —
 * Hungarian says "1 utazás" and "5 utazás" — its two entries simply hold the
 * same word, which keeps the rule in the dictionary where a translator can see
 * it rather than in a branch here.
 *
 * A missing `.one` falls back to the plural, so adding a count somewhere new
 * cannot break a language nobody has got to yet.
 */
export function plural(
  dictionary: Record<string, string>,
  key: TranslationKey,
  count: number,
  vars?: Record<string, string>,
  english?: Record<string, string>,
): string {
  const one = `${key}.one`;
  if (count === 1 && dictionary[one]) {
    return translate(
      { ...dictionary, [key]: dictionary[one] },
      key,
      vars,
      english,
    );
  }
  return translate(dictionary, key, vars, english);
}

/**
 * B376 — the phone field's hint names only the capabilities actually on this
 * server, rather than promising postcards (or WhatsApp) to a reader whose
 * mail the owner cannot act on. `scope` picks between the reader-facing
 * wording (`contact.telHint*`) and the owner's own (`contact.adminTelHint*`,
 * talking about somebody else's number rather than their own).
 */
export function telHintKey(
  scope: "reader" | "admin",
  postcardsEnabled: boolean,
  whatsappEnabled: boolean,
): TranslationKey {
  const prefix = scope === "admin" ? "contact.adminTelHint" : "contact.telHint";
  if (postcardsEnabled && whatsappEnabled) return prefix;
  if (postcardsEnabled) return `${prefix}PostcardsOnly` as TranslationKey;
  if (whatsappEnabled) return `${prefix}WhatsappOnly` as TranslationKey;
  return `${prefix}None` as TranslationKey;
}
